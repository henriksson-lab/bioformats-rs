//! Pure-Rust adapter for FormatTools.openThumbBytes and the AWT calls it uses.
//! Java's area filter averages rendered 8-bit sRGB, not the original samples.

use super::error::BioFormatsError;
use super::metadata::{ImageMetadata, MetadataValue};
use super::pixel_type::PixelType;
use super::reader::FormatReader;
use crate::error::Result;

/// FormatReader.getThumbSizeX/getThumbSizeY (THUMBNAIL_DIMENSION = 128).
pub fn thumbnail_dimensions(meta: &ImageMetadata) -> (u32, u32) {
    let (x, y) = (u64::from(meta.size_x), u64::from(meta.size_y));
    if x < 128 && y < 128 {
        return (x.max(1) as u32, y.max(1) as u32);
    }
    (
        if x > y {
            128
        } else {
            (x * 128 / y.max(1)).max(1) as u32
        },
        if y > x {
            128
        } else {
            (y * 128 / x.max(1)).max(1) as u32
        },
    )
}

/// Java FormatTools.openThumbBytes. Explicit dimensions correspond to the
/// reader's optional CoreMetadata.thumbSizeX/thumbSizeY overrides.
pub fn open_thumb_bytes(
    reader: &mut dyn FormatReader,
    plane_index: u32,
    dimensions: Option<(u32, u32)>,
) -> Result<Vec<u8>> {
    if reader.series_count() == 0 {
        return Err(BioFormatsError::NotInitialized);
    }
    let mut meta = reader.metadata().clone();
    if plane_index >= meta.image_count {
        return Err(BioFormatsError::PlaneOutOfRange(plane_index));
    }
    let channels = if meta.is_rgb {
        match meta.series_metadata.get("rgb_channel_count") {
            Some(MetadataValue::Int(v)) if *v > 0 => *v as usize,
            _ => {
                (meta.size_c / (meta.image_count / meta.size_z.max(1) / meta.size_t.max(1)).max(1))
                    .max(1) as usize
            }
        }
    } else {
        1
    };
    let plane_size = u128::from(meta.size_x)
        * u128::from(meta.size_y)
        * channels as u128
        * meta.pixel_type.bytes_per_sample() as u128;
    let dimensions = dimensions.unwrap_or_else(|| thumbnail_dimensions(&meta));
    if (plane_size as u32 as i32) < 0 {
        // FormatTools reads this centered crop when its signed plane size
        // overflows, but still passes the full dimensions to openImage. AWT
        // cannot construct a raster from that short buffer. Do not allocate a
        // multi-gigabyte full plane or silently substitute another thumbnail.
        let (w, h) = (
            dimensions.0.saturating_mul(4),
            dimensions.1.saturating_mul(4),
        );
        let _ = reader.open_bytes_region(
            plane_index,
            meta.size_x.saturating_sub(w) / 2,
            meta.size_y.saturating_sub(h) / 2,
            w,
            h,
        )?;
        return Err(BioFormatsError::Format(
            "Java thumbnail raster exceeds its cropped source buffer".into(),
        ));
    }
    let bytes = reader.open_bytes(plane_index)?;
    if meta.is_indexed {
        meta.lookup_table = reader.lookup_table(plane_index)?;
    }
    scale_plane(&meta, &bytes, channels, dimensions)
}

