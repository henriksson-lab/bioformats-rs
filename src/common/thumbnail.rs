fn scale_plane(
    meta: &ImageMetadata,
    bytes: &[u8],
    channels: usize,
    dimensions: (u32, u32),
) -> Result<Vec<u8>> {
    let (w, h) = (meta.size_x as usize, meta.size_y as usize);
    let (tw, th) = (dimensions.0 as usize, dimensions.1 as usize);
    let bps = meta.pixel_type.bytes_per_sample();
    let count = w
        .checked_mul(h)
        .and_then(|v| v.checked_mul(channels))
        .ok_or_else(|| BioFormatsError::Format("Thumbnail dimensions overflow".into()))?;
    if w == 0 || h == 0 || tw == 0 || th == 0 || bytes.len() < count * bps {
        return Err(BioFormatsError::Format(
            "Invalid thumbnail source dimensions or byte count".into(),
        ));
    }
    let floating = matches!(meta.pixel_type, PixelType::Float32 | PixelType::Float64);
    let mut normalized = Vec::new();
    if floating {
        // loci.common.DataTools.normalizeFloats/normalizeDoubles deliberately
        // initialize max to MIN_VALUE (smallest positive subnormal), not -MAX.
        let mut min = if bps == 4 { f32::MAX as f64 } else { f64::MAX };
        let mut max = if bps == 4 {
            f32::from_bits(1) as f64
        } else {
            f64::from_bits(1)
        };
        for sample in bytes[..count * bps].chunks_exact(bps) {
            let value = if bps == 4 {
                let v: [u8; 4] = sample.try_into().unwrap();
                (if meta.is_little_endian {
                    f32::from_le_bytes(v)
                } else {
                    f32::from_be_bytes(v)
                }) as f64
            } else {
                let v: [u8; 8] = sample.try_into().unwrap();
                if meta.is_little_endian {
                    f64::from_le_bytes(v)
                } else {
                    f64::from_be_bytes(v)
                }
            };
            if value.is_finite() {
                if value < min {
                    min = value;
                }
                if value > max {
                    max = value;
                }
            }
            normalized.push(value);
        }
        for value in &mut normalized {
            if *value == f64::INFINITY {
                *value = max;
            }
            if *value == f64::NEG_INFINITY {
                *value = min;
            }
            *value = if bps == 4 {
                (((*value as f32) - min as f32) / (max as f32 - min as f32)) as f64
            } else {
                (*value - min) / (max - min)
            };
        }
    }
    if channels >= 3 && matches!(meta.pixel_type, PixelType::Int8 | PixelType::Int32) {
        return Err(BioFormatsError::Format(
            "Java AWT signed RGB color model is incompatible with its packed integer raster".into(),
        ));
    }
    if (w, h) == (tw, th) {
        if !floating {
            return Ok(bytes[..count * bps].to_vec());
        }
        let mut out = Vec::with_capacity(count * bps);
        for value in normalized {
            if bps == 4 {
                let value = if value.is_nan() {
                    f32::from_bits(0x7fc00000)
                } else {
                    value as f32
                };
                out.extend_from_slice(&if meta.is_little_endian {
                    value.to_le_bytes()
                } else {
                    value.to_be_bytes()
                });
            } else {
                let value = if value.is_nan() {
                    f64::from_bits(0x7ff8000000000000)
                } else {
                    value
                };
                out.extend_from_slice(&if meta.is_little_endian {
                    value.to_le_bytes()
                } else {
                    value.to_be_bytes()
                });
            }
        }
        return Ok(out);
    }
    if !(1..=4).contains(&channels)
        || (floating && channels != 1)
        || (matches!(meta.pixel_type, PixelType::Int32 | PixelType::Uint32) && channels != 1)
    {
        return Err(BioFormatsError::Format(
            "Java AWT cannot scale this thumbnail color model/raster combination".into(),
        ));
    }
    if matches!(meta.pixel_type, PixelType::Int32 | PixelType::Uint32) {
        // UnsignedIntColorModel.getDataElements delegates to ComponentColorModel;
        // the integer component mask (1 << 32) - 1 wraps to zero in Java.
        return Ok(vec![0; tw * th * 4]);
    }
    let indexed = if channels == 1 && meta.is_indexed && meta.pixel_type == PixelType::Uint8 {
        meta.lookup_table
            .as_ref()
            .map(super::thumbnail_indexed::IndexedThumbnail::new)
    } else {
        None
    };
    let mut rendered = vec![[0.0f32; 4]; w * h];
    for (pixel, rgba) in rendered.iter_mut().enumerate() {
        rgba[3] = 255.0;
        for channel in 0..channels {
            let index = if meta.is_interleaved {
                pixel * channels + channel
            } else {
                channel * w * h + pixel
            };
            let value = if floating {
                normalized[index]
            } else if bps == 1 {
                bytes[index] as f64 / 255.0
            } else {
                let sample: [u8; 2] = bytes[index * 2..index * 2 + 2].try_into().unwrap();
                f64::from(if meta.is_little_endian {
                    u16::from_le_bytes(sample)
                } else {
                    u16::from_be_bytes(sample)
                }) / 65535.0
            };
            let encoded = if channels == 1 {
                let linear =
                    ((value as f32 * 65535.0 + 0.5) as i32).clamp(0, 65535) as f32 / 65535.0;
                let srgb = if linear <= 0.0031308 {
                    linear * 12.92
                } else {
                    (1.055 * (linear as f64).powf(1.0 / 2.4) - 0.055) as f32
                };
                (srgb * 255.0 + 0.5) as i32
            } else {
                (value as f32 * 255.0 + 0.5) as i32
            }
            .clamp(0, 255) as f32;
            rgba[channel] = encoded;
            if channels == 1 {
                rgba[1] = encoded;
                rgba[2] = encoded;
            }
        }
        if rgba[3] != 255.0 {
            let alpha = rgba[3] / 255.0;
            for value in &mut rgba[..3] {
                *value *= alpha;
            }
        }
    }
    let mut out = vec![0u8; tw * th * channels * bps];
    // java.awt.image.AreaAveragingScaleFilter.accumPixels/calcRow: use integer
    // overlap weights and float accumulators, including alpha premultiplication.
    let area = w as f32 * h as f32;
    for dy in 0..th {
        for dx in 0..tw {
            let mut sums = [0.0f32; 4];
            for sy in dy * h / th..((dy + 1) * h).div_ceil(th) {
                let wy = ((sy + 1) * th).min((dy + 1) * h) - (sy * th).max(dy * h);
                for sx in dx * w / tw..((dx + 1) * w).div_ceil(tw) {
                    let wx = ((sx + 1) * tw).min((dx + 1) * w) - (sx * tw).max(dx * w);
                    let weight = wx as f32 * wy as f32;
                    for channel in 0..4 {
                        sums[channel] += weight * rendered[sy * w + sx][channel];
                    }
                }
            }
            let alpha = (sums[3] / area + 0.5).floor().clamp(0.0, 255.0);
            let divisor = if alpha > 0.0 && alpha < 255.0 {
                sums[3] / 255.0
            } else {
                area
            };
            for channel in 0..channels {
                let mut value = if channel == 3 {
                    alpha
                } else {
                    (sums[channel] / divisor + 0.5).floor().clamp(0.0, 255.0)
                };
                if channels == 4 && channel < 3 && alpha > 0.0 && alpha < 255.0 {
                    // ToolkitImage stores the area filter's ARGB through an
                    // 8-bit premultiplied intermediate before Graphics2D draws
                    // into the destination ColorModel.
                    let premultiplied = (value as u32 * alpha as u32 + 127) / 255;
                    // Java2D div8table uses a rounded 24-bit reciprocal.
                    let reciprocal = ((255u64 << 24) + alpha as u64 / 2) / alpha as u64;
                    value = ((premultiplied as u64 * reciprocal + (1 << 23)) >> 24).min(255) as f32;
                }
                let index = if meta.is_interleaved {
                    (dy * tw + dx) * channels + channel
                } else {
                    channel * tw * th + dy * tw + dx
                } * bps;
                if floating {
                    let value = if channels == 1 {
                        if bps == 4 {
                            f32::from_bits(SRGB_TO_LINEAR_GRAY[value as usize]) as f64
                        } else {
                            f64::from_bits(SRGB_TO_LINEAR_GRAY_DOUBLE[value as usize])
                        }
                    } else {
                        value as f64 / 255.0
                    };
                    if bps == 4 {
                        let value = value as f32;
                        out[index..index + 4].copy_from_slice(&if meta.is_little_endian {
                            value.to_le_bytes()
                        } else {
                            value.to_be_bytes()
                        });
                    } else {
                        out[index..index + 8].copy_from_slice(&if meta.is_little_endian {
                            value.to_le_bytes()
                        } else {
                            value.to_be_bytes()
                        });
                    }
                } else if bps == 1 {
                    out[index] = indexed
                        .as_ref()
                        .map_or(value as u8, |palette| palette.index(value as u8, dx, dy));
                } else {
                    let value = value as u16
                        * if meta.is_indexed
                            && meta.lookup_table.is_some()
                            && meta.pixel_type == PixelType::Uint16
                        {
                            1
                        } else {
                            257
                        };
                    out[index..index + 2].copy_from_slice(&if meta.is_little_endian {
                        value.to_le_bytes()
                    } else {
                        value.to_be_bytes()
                    });
                }
            }
        }
    }
    Ok(out)
}

